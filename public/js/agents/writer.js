/**
 * agents/writer.js — Writer Agent (03)
 *
 * Generates a structured CV draft and a personalised cover letter
 * from the user's CV text and analysis result.
 * All generation is done client-side — no LLM API required.
 */

import { state }       from '../state.js';
import { updateStats, syncWriterCv, setAgentStatus } from './scout.js';

const $ = id => document.getElementById(id);
const esc = s => String(s||'').replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');

// ── CV generator ──────────────────────────────────────────────────────────

function buildCV(cvText, targetJob, analysis) {
  const skills  = analysis?.foundSkills?.map(s => s.label) || [];
  const topRole = targetJob || analysis?.roles?.[0]?.name || 'Cybersecurity Professional';
  const date    = new Date().toLocaleDateString('en-GB');

  return `╔══════════════════════════════════════════════════════╗
║          CURRICULUM VITAE — CareerAI Draft           ║
╚══════════════════════════════════════════════════════╝

PROFESSIONAL PROFILE
──────────────────────────────────────────────────────
Results-driven ${topRole} with expertise in${
  skills.length ? ' ' + skills.slice(0, 4).join(', ') : ' cybersecurity operations'
}.

  Target Role:  ${topRole}
  Generated:    ${date}

CORE COMPETENCIES
──────────────────────────────────────────────────────
${skills.length ? skills.map(s => `  ✓  ${s}`).join('\n') : '  ✓  [Add your key skills here]'}

PROFESSIONAL EXPERIENCE
──────────────────────────────────────────────────────
${cvText.split('\n').filter(l => l.trim()).slice(0, 30).map(l => '  ' + l).join('\n')}

EDUCATION
──────────────────────────────────────────────────────
  [Degree · Institution · Year]

CERTIFICATIONS
──────────────────────────────────────────────────────
  [CompTIA Security+, CEH, CISSP, or equivalent]

TECHNICAL SKILLS
──────────────────────────────────────────────────────
${skills.length ? skills.map(s => `  •  ${s}`).join('\n') : '  •  [List your technical skills here]'}

──────────────────────────────────────────────────────
Generated by CareerAI Writer Agent`;
}

// ── Cover letter generator ────────────────────────────────────────────────

function buildCoverLetter({ jobTitle, company, name, skills: skillsStr }) {
  const skillList = (skillsStr || '').split(',').map(s => s.trim()).filter(Boolean);
  const date      = new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
  const topSkills = skillList.length ? skillList.slice(0, 3).join(', ') : 'cybersecurity analysis and problem-solving';

  return `${name || '[Your Name]'}
[Address · City · Country]  |  [your@email.com]  |  [+xx xxx xxxxxx]

${date}

Hiring Manager
${company || '[Company Name]'}

Dear Hiring Team,

Re: Application for ${jobTitle || '[Job Title]'}

I am writing to express my strong interest in the ${jobTitle || '[Job Title]'} position at ${company || '[Company]'}. With hands-on experience in ${topSkills}, I am confident in my ability to contribute meaningfully to your team.

${skillList.length ? `My key competencies:\n${skillList.map(s => `  •  ${s}`).join('\n')}\n` : ''}
My background has equipped me with a thorough understanding of the evolving threat landscape and best practices for protecting critical systems. I take a proactive approach to identifying risks and implementing security controls.

I am drawn to ${company || 'your organisation'} because of your commitment to excellence in this field. I believe my skills and dedication make me an excellent fit for this role.

I would welcome the opportunity to discuss how my experience aligns with your team's needs.

Yours sincerely,
${name || '[Your Name]'}

────────────────────────────────────────────────────────
Generated by CareerAI Writer Agent`;
}

// ── Helpers ───────────────────────────────────────────────────────────────

function copyText(id) {
  const el = $(id);
  if (!el) return;
  navigator.clipboard.writeText(el.value).catch(() => { el.select(); document.execCommand('copy'); });
}

function downloadText(id, filename) {
  const el = $(id);
  if (!el) return;
  const a = Object.assign(document.createElement('a'), {
    href:     URL.createObjectURL(new Blob([el.value], { type: 'text/plain' })),
    download: filename
  });
  a.click();
}

// ── Init ──────────────────────────────────────────────────────────────────

export function initWriter() {
  $('generate-cv-btn').addEventListener('click', () => {
    const cvText = $('cv-for-writer').value.trim();
    if (!cvText) { alert('Paste your CV text or run the Scout Agent first.'); return; }
    setAgentStatus('writer', 'running');
    $('generated-cv-output').value = buildCV(cvText, $('target-job-input').value.trim(), state.analysis);
    $('cv-output-block').classList.remove('hidden');
    setAgentStatus('writer', 'done');
    state.docsCount++;
    updateStats();
  });

  $('generate-cover-btn').addEventListener('click', () => {
    setAgentStatus('writer', 'running');
    $('generated-cover-output').value = buildCoverLetter({
      jobTitle: $('cover-job-title').value.trim(),
      company:  $('cover-company').value.trim(),
      name:     $('cover-name').value.trim(),
      skills:   $('cover-skills').value.trim()
    });
    $('cover-output-block').classList.remove('hidden');
    setAgentStatus('writer', 'done');
    state.docsCount++;
    updateStats();
  });

  $('copy-cv-btn').addEventListener('click',      () => copyText('generated-cv-output'));
  $('download-cv-btn').addEventListener('click',  () => downloadText('generated-cv-output', 'cv-draft.txt'));
  $('copy-cover-btn').addEventListener('click',   () => copyText('generated-cover-output'));
  $('download-cover-btn').addEventListener('click',() => downloadText('generated-cover-output', 'cover-letter.txt'));
}
